from base64 import b64encode
from io import BytesIO
from json import dumps
from pathlib import Path

from PIL import Image, ImageDraw, ImageOps

root = Path(__file__).resolve().parents[1]
with Image.open(root / "assets" / "brand-master.png") as source:
    original = ImageOps.fit(source.convert("RGB"), (512, 512), method=Image.Resampling.LANCZOS)

corner_mask = Image.new("L", original.size)
ImageDraw.Draw(corner_mask).rounded_rectangle((0, 0, 511, 511), radius=105, fill=255)
mark = original.convert("RGBA")
mark.putalpha(corner_mask)

def encode_png(image, size):
    buffer = BytesIO()
    image.resize((size, size), Image.Resampling.LANCZOS).save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()

def encode_ico(image):
    buffer = BytesIO()
    image.save(buffer, format="ICO", sizes=[(n, n) for n in (16, 24, 32, 48)])
    return buffer.getvalue()

files = {
    "ico": encode_ico(mark),
    "tab": encode_png(mark, 32),
    "logo": encode_png(mark, 96),
    "apple": encode_png(original, 180),
}

with Image.open(BytesIO(files["ico"])) as ico:
    assert ico.ico.sizes() == {(16, 16), (24, 24), (32, 32), (48, 48)}

encoded = {name: b64encode(data).decode("ascii") for name, data in files.items()}
target = root / "src" / "brand-files.mjs"
target.write_text("// Generated by tools/build_brand.py from assets/brand-master.png.\n"
                  + "export const brandFiles = " + dumps(encoded, indent=2) + ";\n", encoding="utf-8")
